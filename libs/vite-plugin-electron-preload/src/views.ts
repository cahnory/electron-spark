import fs from "node:fs";
import path from "node:path";

import { buildOnServe, waitForBuildOnServe } from "@electron-spark/vite-plugin-build-on-serve";
import { normalizePath, type Plugin } from "vite";

import { electronPreloadRenderer } from "./renderer.ts";
import { preloadEntries, runtimeHelper } from "./shared.ts";

export type PreloadView = {
  /** HTML entry, relative to Vite's root. */
  html: string;
  /** Environment that builds this view's aggregate preload. */
  environment: string;
  /** Generated aggregate source filename. */
  entry: string;
};

export type ElectronPreloadViewsOptions = {
  preloadPatterns: string | readonly string[];
  views: readonly PreloadView[];
  clientEnvironment?: string;
};

/** Discover preload boundaries in Vite's graph and generate one aggregate per view. */
export function electronPreloadViews(options: ElectronPreloadViewsOptions): Plugin[] {
  const client = options.clientEnvironment ?? "client";
  const entries = preloadEntries(options);
  let root: string;
  const collector: Plugin = {
    name: "@electron-spark/vite-plugin-electron-preload:views",
    configResolved(config) {
      root = config.root;
      entries.configure(config);
    },
    buildEnd(error) {
      // Discovery watches skip output generation. Collect after graph construction,
      // before their successful END event releases the dependent preload builds.
      if (error || this.environment.mode !== "build" || this.environment.name !== client) return;
      for (const view of options.views) {
        const visited = new Set<string>();
        const preloads = new Set<string>();
        const visit = (id: string) => {
          if (visited.has(id)) return;
          visited.add(id);
          if (entries.has(id)) {
            preloads.add(id);
            return;
          }
          const module = this.getModuleInfo(id);
          if (!module) return;
          for (const dependency of [...module.importedIds, ...module.dynamicallyImportedIds]) {
            visit(dependency);
          }
        };
        const html = normalizePath(path.resolve(root, view.html));
        if (!this.getModuleInfo(html)) {
          this.error(
            `Cannot discover preload imports: renderer HTML is missing from the build: ${html}`,
          );
        }
        visit(html);
        const sources = [...preloads].toSorted();
        const imports = sources.map(
          (source, index) => `import * as preload${index} from ${JSON.stringify(source)};`,
        );
        const properties = sources.map(
          (source, index) => `  [${JSON.stringify(entries.key(source))}]: preload${index},`,
        );
        const code = [
          "// Generated by electronPreloadViews. Do not edit.",
          ...imports,
          `import { exposeToRenderer } from ${JSON.stringify(runtimeHelper("exposeToRenderer"))};`,
          "exposeToRenderer({",
          ...properties,
          "});",
          "",
        ].join("\n");
        const file = path.resolve(root, view.entry);
        if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== code) {
          fs.mkdirSync(path.dirname(file), { recursive: true });
          fs.writeFileSync(file, code);
        }
      }
    },
  };
  return [
    electronPreloadRenderer(options),
    collector,
    // Build the renderer graph before starting preload watchers, without writing
    // renderer assets. Watching this graph also catches new/removed imports.
    ...(options.views.length
      ? [
          buildOnServe(client, {
            build: { write: false, emptyOutDir: false, watch: { skipWrite: true } },
            session(server) {
              const ready = Promise.withResolvers<void>();
              for (const view of options.views) {
                waitForBuildOnServe(server, view.environment, ready.promise);
              }
              return {
                buildSuccess() {
                  ready.resolve();
                },
                async close() {
                  ready.resolve();
                },
              };
            },
          }),
        ]
      : []),
    ...options.views.map((view) =>
      buildOnServe(view.environment, {
        session(server) {
          return {
            buildSuccess() {
              server.ws.send({ type: "full-reload" });
            },
            async close() {},
          };
        },
      }),
    ),
  ];
}
